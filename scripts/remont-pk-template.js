/* Sprzątanie po remoncie "POD KLUCZ" — one price per m² (55 zł) + soiling level.
   GENERATED by scripts/build-remont-pk.pl from scripts/remont-pk-texts.json + this template — edit those, not the output.
   Loaded last on the four post-renovation pages: it replaces the old bracket calculator (renderRows / updateOrder /
   submitOrder / setTier / initWindowPicker) and re-applies its own texts after the page's applyTranslations().
   Price rule: base = area × 55 zł. Light = shown as a 95–100 % range, standard = base, heavy = base + a note about a
   possible individual surcharge (up to 25 %). Neither the 5 % discount nor the 25 % surcharge is ever applied
   automatically: the order carries the base price as a preliminary figure. */
(function(){
  'use strict';
  var RATE = 55, LIGHT_FACTOR = 0.95;
  var TXT = /*__TEXTS__*/null;
  var HTML = /*__HTML__*/null;
  var st = { m2: 0, lvl: 1 };       // lvl: 0 light, 1 standard, 2 heavy

  function L(){ return (typeof lang !== 'undefined' && TXT[lang]) ? lang : 'pl'; }
  function T(){ return TXT[L()]; }
  function f(s, v){ return String(s).replace(/\{(\w+)\}/g, function(_, k){ return v && v[k] !== undefined ? v[k] : ''; }); }
  function money(n){ return fmt(n); }
  function plain(n){ return fmt(n).replace(/\s*zł$/, ''); }
  function esc(s){ return String(s).replace(/[&<>"]/g, function(c){ return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]; }); }

  function base(){ return st.m2 > 0 ? Math.round(st.m2 * RATE) : 0; }
  function low(){ return Math.round(base() * LIGHT_FACTOR); }

  function addonsTotal(){
    return (typeof selectedAddons !== 'undefined' ? selectedAddons : []).reduce(function(s, a){ return s + a.price; }, 0);
  }

  /* ---------- calculator ---------- */
  function renderCalc(){
    var wrap = document.getElementById('calc-rows');
    if(!wrap) return;
    var t = T(), h = '';
    h += '<div class="pk-field"><label class="pk-lbl" for="pk-area">' + esc(t.areaLbl) + '</label>' +
         '<div class="calc-inp-row"><input class="calc-inp pk-area" type="number" id="pk-area" min="1" step="any" inputmode="decimal" placeholder="' + esc(t.areaPh) + '" autocomplete="off" oninput="pkArea(this)">' +
         '<span class="calc-unit">m²</span></div></div>';
    h += '<div class="pk-lbl pk-lbl-lvl">' + esc(t.levelLbl) + '</div>';
    for(var i = 0; i < 3; i++){
      h += '<div class="calc-row calc-fixed pk-lvl' + (st.lvl === i ? ' active' : '') + '" id="pk-l' + i + '">' +
           '<div class="calc-row-hdr" onclick="pkLevel(' + i + ')"><div class="calc-radio">✓</div>' +
           '<span class="calc-lbl">' + esc(t.lvl[i]) + '<small>' + esc(t.lvlSub[i]) + '</small></span></div></div>';
    }
    h += '<div class="calc-result" id="pk-res"></div>';
    h += '<p class="calc-hint pk-large" id="pk-large">' + esc(t.large) + '</p>';
    h += '<p class="calc-hint pk-large" id="pk-time">' + esc(t.timeNote) + '</p>';
    wrap.innerHTML = h;
    var inp = document.getElementById('pk-area');
    if(inp && st.m2 > 0) inp.value = st.m2;
    renderResult();
  }

  function renderResult(){
    var res = document.getElementById('pk-res');
    if(!res) return;
    var inp = document.getElementById('pk-area');
    var t = T(), b = base();
    if(!(st.m2 > 0)){
      if(window.vcAreaInputFilled && inp && vcAreaInputFilled(inp)){ res.className = 'calc-result err show'; res.textContent = window.vcAreaZeroMsg ? vcAreaZeroMsg() : t.errArea; }
      else { res.className = 'calc-result'; res.textContent = ''; }
      return;
    }
    var line = f(t.resBase, {m2: st.m2}) + ' = ' + money(b);
    var detail = st.lvl === 0 ? f(t.resLight, {lo: plain(low()), base: plain(b)})
               : st.lvl === 2 ? f(t.resStrong, {base: plain(b)})
               : f(t.resStd, {base: plain(b)});
    res.className = 'calc-result show';
    res.innerHTML = '✅ <strong>' + esc(line) + '</strong><br><span class="pk-res-detail">' + esc(detail) + '</span><br><span class="pk-res-detail">' + esc(t.prelim) + '</span>';
  }

  window.pkArea = function(inp){
    var v = parseFloat(String(inp.value).replace(',', '.'));
    st.m2 = (v > 0 && isFinite(v)) ? v : 0;
    renderResult();
    window.updateOrder();
  };
  window.pkLevel = function(i){
    st.lvl = i;
    for(var k = 0; k < 3; k++){ var r = document.getElementById('pk-l' + k); if(r) r.classList.toggle('active', k === i); }
    renderResult();
    window.updateOrder();
  };

  /* ---------- sidebar / totals ---------- */
  window.updateOrder = function(){
    var lines = document.getElementById('order-lines');
    var totalEl = document.getElementById('order-total');
    var mobTotal = document.getElementById('mob-total');
    var cta = document.getElementById('order-cta');
    var t = T(), b = base(), html = '', total = 0;
    if(b > 0){
      var key = st.lvl === 0 ? 'orderLineLight' : st.lvl === 2 ? 'orderLineStrong' : 'orderLineStd';
      html += '<div class="order-line"><div class="ol-name">' + esc(f(t[key], {svc: t.svcName, m2: st.m2})) + '</div><div class="ol-val">' + (st.lvl === 0 ? esc(plain(low())) + '–' + esc(money(b)) : esc(money(b))) + '</div></div>';
      if(st.lvl === 0) html += '<div class="order-line"><div class="ol-name pk-note">' + esc(f(t.orderNoteLight, {lo: plain(low()), base: plain(b)})) + '</div></div>';
      if(st.lvl === 2) html += '<div class="order-line"><div class="ol-name pk-note">' + esc(f(t.orderNoteStrong, {base: plain(b)})) + '</div></div>';
      total += b;
    }
    (typeof selectedAddons !== 'undefined' ? selectedAddons : []).forEach(function(a){
      html += '<div class="order-line"><div class="ol-name">' + a.name + '</div><div class="ol-val">' + money(a.price) + '</div></div>';
      total += a.price;
    });
    if(!html) html = '<div class="order-empty">' + esc(t.sidebarEmpty) + '</div>';
    if(lines) lines.innerHTML = html;
    var label = money(total);
    if(b > 0 && st.lvl === 0) label = f(t.totalLight, {n: money(total)});
    if(b > 0 && st.lvl === 2) label = f(t.totalStrong, {n: money(total)});
    if(totalEl) totalEl.textContent = label;
    if(mobTotal) mobTotal.textContent = label;
    if(cta) cta.disabled = !(total > 0);
    var mobBar = document.getElementById('mob-bar');
    if(mobBar){
      if(total > 0){ mobBar.classList.add('show'); document.body.classList.add('has-order'); }
      else { mobBar.classList.remove('show'); document.body.classList.remove('has-order'); }
    }
    if(window.VCInfoCard) VCInfoCard.hide('remont');   // its time/crew bands belonged to the old area brackets
  };

  /* ---------- submit (same booking path as before; only the data changed) ---------- */
  window.submitOrder = function(){
    var t = T();
    var b = base(), total = b + addonsTotal();
    if(total <= 0){ alert((TX[lang] || TX.pl).submit_no_service); return; }
    if(maybeShowOzonUpsell(window.submitOrder)) return;
    var extrasArr = selectedAddons.map(function(a){ return a.name; });
    var serviceLabel = t.svcName + " · " + st.m2 + " m²";
    var levelRow = t.lvlLabel + ": " + t.lvlName[st.lvl];
    var note = st.lvl === 0 ? f(t.orderNoteLight, {lo: plain(low()), base: plain(b)})
               : st.lvl === 2 ? f(t.orderNoteStrong, {base: plain(b)}) : "";
    var prelim = t.prelim + (note ? " (" + note.replace(/^[^:]+:\s*/, "") + ")" : "");
    bk_orderData = {
      service: serviceLabel,                                   // plain service name + area only
      serviceNotes: [levelRow, prelim],                        // shown in the booking recap; not part of the service name
      cleaningLevel: ["light", "standard", "heavy"][st.lvl],   // structured, separate from the service name
      analyticsLabel: t.svcName,
      serviceSlug: 'sprzatanie-po-remoncie',
      area: st.m2 + ' m²',
      areaRange: '',
      extras: extrasArr.join(', '),
      addons: selectedAddons.filter(function(a){ return a.price > 0; }).map(function(a){
        return { key: 'pr:' + a.nameId, qty: a.qty, price: a.price };
      }),
      areaM2: st.m2,
      windows: null,                       // window cleaning is part of the package — never a separate, second charge
      serviceLines: b > 0 ? [{ slug: 'sprzatanie-po-remoncie', m2: st.m2, price: b, qty: 1 }] : null,
      price: total
    };
    bk_renderOrder();
    var sec = document.getElementById('bk-inline-section');
    if(sec){
      sec.classList.remove('bk-hidden');
      setTimeout(function(){ sec.scrollIntoView({behavior: 'smooth', block: 'start'}); }, 80);
    }
  };

  /* ---------- neutralise the old bracket / window-picker entry points ---------- */
  window.renderRows = renderCalc;
  window.setTier = function(){};
  window.initWindowPicker = function(){};

  /* ---------- static texts (also written into the HTML at build time, for crawlers) ---------- */
  function setHtml(id, v){ var el = document.getElementById(id); if(el) el.innerHTML = v; }
  function setFaq(i, q, a){
    var qe = document.getElementById('faq-q' + i), ae = document.getElementById('faq-a' + i);
    if(qe) qe.innerHTML = esc(q) + ' <span class="faq-arrow">▼</span>';
    if(ae) ae.textContent = a;
  }
  function applyTexts(){
    var t = T(), l = L();
    setHtml('hero-badge', t.badge);
    setHtml('hero-h1', t.h1);
    setHtml('hero-sub', esc(t.sub));
    setHtml('tier-meta', t.meta);
    setHtml('calc-title', t.calcTitle);
    setHtml('calc-sub', esc(t.calcSub));
    setHtml('calc-extras', esc(t.calcExtras));
    var sec = document.getElementById('scope-section');
    if(sec && HTML[l]) sec.innerHTML = HTML[l].scope;
    setFaq(0, t.faq0q, t.faq0a);
    setFaq(6, t.faq6q, t.faq6a);
    document.title = t.title;
  }

  function apply(){
    applyTexts();
    renderCalc();
    window.updateOrder();
  }

  var origApply = window.applyTranslations;
  if(typeof origApply === 'function'){
    window.applyTranslations = function(){
      var r = origApply.apply(this, arguments);
      apply();
      return r;
    };
  }

  // Prefill from the home-page quick-quote widget (?m2=…).
  try {
    var q = parseFloat((new URLSearchParams(location.search)).get('m2'));
    if(q > 0) st.m2 = q;
  } catch(e) {}

  // Old deep links (#z / #bez, from the former furniture tabs) now lead to the new calculator.
  function toCalc(){
    if(/^#(z|bez)$/.test(location.hash)){
      var c = document.getElementById("cennik-kalkulator");
      if(c) c.scrollIntoView({behavior: "smooth", block: "start"});
    }
  }
  window.addEventListener("load", function(){ setTimeout(toCalc, 400); });
  window.addEventListener("hashchange", toCalc);

  apply();
})();
